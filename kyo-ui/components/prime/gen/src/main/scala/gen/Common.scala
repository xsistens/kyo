package gen

import java.nio.file.Files
import java.nio.file.Path

object Common:
    /** Pinned upstream versions the gitignored inputs are fetched at (see fetch.sh and npm/package.json). */
    val UI5Version        = "2.24.0" // legacy: @ui5/webcomponents-icons (FioriIcons)
    val PrimeUixVersion   = "2.0.3"  // @primeuix/{styles,themes} (see gen/npm/package.json)
    val PrimeIconsVersion = "7.0.0"

    val GeneratedHeader =
        s"// GENERATED by kyo-ui-components gen from @ui5/webcomponents $UI5Version; do not edit manually.\n"

    def header(source: String): String =
        s"// GENERATED by kyo-ui-components gen from $source; do not edit manually.\n"

    /** This project's directory relative to the kyo repo root (see `kyo-ui-components-gen` in build.sbt). */
    private val GenRelPath = "kyo-ui/components/prime/gen"

    /** Repo root: the nearest ancestor of the working dir that holds both `build.sbt` and this project.
      * sbt runs the generator from the build root, but the search keeps a run from any subdirectory
      * (including the gen directory itself) pointed at the same tree.
      */
    lazy val repoRoot: Path =
        Iterator
            .iterate(Path.of(System.getProperty("user.dir")).toAbsolutePath)(_.getParent)
            .takeWhile(_ != null)
            .find(p => Files.exists(p.resolve("build.sbt")) && Files.isDirectory(p.resolve(GenRelPath)))
            .getOrElse(sys.error(s"no kyo repo root (build.sbt + $GenRelPath) above " + System.getProperty("user.dir")))

    /** The generator project directory; `fetch.sh` populates `input/`, `work/` and `npm/node_modules/` under it. */
    lazy val genDir: Path     = repoRoot.resolve(GenRelPath)
    lazy val inputDir: Path   = genDir.resolve("input")
    lazy val workDir: Path    = genDir.resolve("work")
    lazy val npmModules: Path = genDir.resolve("npm/node_modules")
    lazy val outputDir: Path  = repoRoot.resolve("kyo-ui/components/prime/shared/src/main/scala/kyo/uic/generated")

    /** Scala hard keywords that must be backtick-escaped as identifiers. */
    private val scalaKeywords = Set(
        "abstract",
        "case",
        "catch",
        "class",
        "def",
        "do",
        "else",
        "enum",
        "export",
        "extends",
        "false",
        "final",
        "finally",
        "for",
        "given",
        "if",
        "implicit",
        "import",
        "lazy",
        "match",
        "new",
        "null",
        "object",
        "override",
        "package",
        "private",
        "protected",
        "return",
        "sealed",
        "super",
        "then",
        "this",
        "throw",
        "trait",
        "true",
        "try",
        "type",
        "val",
        "var",
        "while",
        "with",
        "yield"
    )

    /** kebab-case (and digit-leading) icon/member names → legal Scala camelCase idents. */
    def toIdent(kebab: String): String =
        val parts = kebab.split('-').filter(_.nonEmpty)
        val camel = parts.head + parts.tail.map(_.capitalize).mkString
        val legal = if camel.headOption.exists(_.isDigit) then "_" + camel else camel
        if scalaKeywords(legal) then s"`$legal`" else legal
    end toIdent

    def write(path: Path, content: String): Unit =
        Files.createDirectories(path.getParent)
        Files.writeString(path, content)
        println(s"wrote $path (${content.length} chars)")
    end write
end Common
